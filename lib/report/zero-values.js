'use strict';

const { CliError } = require('../core/cli-error');
const { t } = require('../core/i18n');
const { buildAfterFetch } = require('./field-utils');

/**
 * Runs after aggregation in the native chart, with a fresh query's metadata.
 * Metadata must be edited in place: the native data state derives yField roles
 * from this same array. Never mutate source records or permanently hide fields
 * in dataSetModelMap, so a later nonzero result restores the series.
 */
function openyidaHideZeroValues(data, extraInfo) {
  const hideZeroCategories = false;
  const hideZeroLegends = false;
  if (!Array.isArray(data) || !extraInfo || !Array.isArray(extraInfo.meta)) {return data;}
  const meta = extraInfo.meta;
  const keys = meta.filter(function (item) {
    return item && item.category === 'yField' && typeof item.alias === 'string';
  }).map(function (item) {return item.alias;});
  if (!keys.length) {return data;}

  function hasValue(value) {
    if (value === null || value === undefined) {return false;}
    if (typeof value === 'string' && !value.trim()) {return false;}
    return !((typeof value === 'number' || typeof value === 'string') && Number(value) === 0);
  }

  const active = keys.filter(function (key) {
    return data.some(function (row) {return row && hasValue(row[key]);});
  });
  if (hideZeroLegends) {
    for (let index = meta.length - 1; index >= 0; index--) {
      if (meta[index] && meta[index].category === 'yField' && active.indexOf(meta[index].alias) < 0) {
        meta.splice(index, 1);
      }
    }
  }
  return data.filter(function (row) {
    return row && (!hideZeroCategories || active.some(function (key) {return hasValue(row[key]);}));
  }).map(function (row) {
    const next = Object.assign({}, row);
    keys.forEach(function (key) {
      if (!hasValue(next[key])) {next[key] = null;}
    });
    return next;
  });
}

const SOURCE = openyidaHideZeroValues.toString();

/** Build the native editor's source/compiled function shape, without eval. */
function buildZeroValueAfterFetch(options = {}) {
  const source = SOURCE
    .replace('const hideZeroCategories = false;', 'const hideZeroCategories = ' + (options.hideZeroCategories === true) + ';')
    .replace('const hideZeroLegends = false;', 'const hideZeroLegends = ' + (options.hideZeroLegends === true) + ';');
  return { type: 'js', source, compiled: source };
}

/** Read source only; a marker substring is insufficient to claim ownership. */
function afterFetchSource(value) {
  if (typeof value === 'string') {return value;}
  if (!value || typeof value !== 'object') {return '';}
  return typeof value.source === 'string' ? value.source
    : typeof value.value === 'string' ? value.value : '';
}

/** Identify precisely the code generated by this CLI, including editor recompilation. */
function isZeroValueAfterFetch(value) {
  return getZeroValueOptions(value) !== null;
}

/** Recognize only the four exact CLI-owned variants; never infer custom code behavior. */
function getZeroValueOptions(value) {
  if (value && typeof value === 'object' && value.id) {return null;}
  const source = afterFetchSource(value).trim();
  for (const hideZeroCategories of [false, true]) {
    for (const hideZeroLegends of [false, true]) {
      const options = { hideZeroValues: true, hideZeroCategories, hideZeroLegends };
      if (source === buildZeroValueAfterFetch(options).source) {return options;}
    }
  }
  return null;
}

/** Only absent hooks and the CLI's known identity hook may be replaced. */
function canConfigureAfterFetch(value) {
  if (value === undefined || value === null || value === '') {return true;}
  if (typeof value === 'object' && value.id) {return false;}
  const source = afterFetchSource(value).trim();
  return isZeroValueAfterFetch(value) || source === buildAfterFetch().value;
}

/** Validate explicit opt-in before any remote write; other chart roles are unaudited. */
function zeroValueConfigIssues(chart, path) {
  const issues = [];
  if (!chart || typeof chart !== 'object') {return issues;}
  for (const key of ['hideZeroValues', 'hideZeroCategories', 'hideZeroLegends']) {
    if (chart[key] !== undefined && typeof chart[key] !== 'boolean') {
      issues.push({ code: 'REPORT_ZERO_VALUES_INVALID', path: path + '.' + key,
        message: t('report_runtime.zero_boolean', key) });
    }
  }
  if (chart.hideZeroValues !== true && (chart.hideZeroCategories === true || chart.hideZeroLegends === true)) {
    issues.push({ code: 'REPORT_ZERO_VALUES_INVALID', path,
      message: t('report_runtime.zero_requires_enabled') });
  }
  if (chart.hideZeroValues === true) {
    if (String(chart.type || '').trim().toLowerCase() !== 'bar') {
      issues.push({ code: 'REPORT_ZERO_VALUES_UNSUPPORTED', path: path + '.hideZeroValues',
        message: t('report_runtime.zero_supported') });
    }
    if (!canConfigureAfterFetch(chart.afterFetch)) {
      issues.push({ code: 'REPORT_ZERO_VALUES_CUSTOM_HOOK', path: path + '.afterFetch',
        message: t('report_runtime.zero_custom_hook') });
    }
  }
  return issues;
}

/** Protect user code and reject unaudited schemas even when called without validation. */
function configureZeroValues(props, enabled, options = {}) {
  if (!canConfigureAfterFetch(props.afterFetch)) {
    throw new CliError(t('report_runtime.zero_custom_hook'), { code: 'REPORT_ZERO_VALUES_CUSTOM_HOOK' });
  }
  const previous = getZeroValueOptions(props.afterFetch);
  const next = { hideZeroCategories: previous?.hideZeroCategories || false,
    hideZeroLegends: previous?.hideZeroLegends || false, ...options, hideZeroValues: enabled, type: 'bar' };
  if (!enabled) {
    next.hideZeroCategories = options.hideZeroCategories === true;
    next.hideZeroLegends = options.hideZeroLegends === true;
  }
  const issues = zeroValueConfigIssues(next, 'chart');
  if (issues.length) {throw new CliError(issues[0].message, { code: issues[0].code });}
  if ((!enabled && !previous) || (enabled && previous
    && previous.hideZeroCategories === next.hideZeroCategories && previous.hideZeroLegends === next.hideZeroLegends)) {return false;}
  props.afterFetch = enabled ? buildZeroValueAfterFetch(next) : buildAfterFetch();
  return true;
}

module.exports = {
  buildZeroValueAfterFetch,
  canConfigureAfterFetch,
  configureZeroValues,
  isZeroValueAfterFetch,
  getZeroValueOptions,
  zeroValueConfigIssues,
};
